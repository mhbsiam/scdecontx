"""scdecontx (celda's DecontX) on the soup scenarios of tests/_soup.py.

Usage:
    python scripts/scenarios.py [--quick]

Each scenario breaks one assumption of the DecontX model. S0 keeps them
all; S6 breaks them all. The script fits every dataset with and without
the empty droplets as background. It scores each fit against the oracle:
the posterior under the true parameters, which no method can beat on
average. The per-run metrics go to results/scenarios.csv and the summary
to results/scenarios.md.
"""

import argparse
import sys
import time
import warnings
from pathlib import Path

import anndata as ad
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
from _soup import SCENARIOS, oracle, score, simulate_soup  # noqa: E402

import scdecontx as dx  # noqa: E402

RESULTS = HERE.parent / "results"
# delta = (1, 30) gives ~3% contamination (as in the human-mouse mixture),
# (1, 10) ~9% and (4, 6) ~40%.
LEVELS = {"3%": (1.0, 30.0), "9%": (1.0, 10.0), "40%": (4.0, 6.0)}
SEEDS = (1, 2, 3)
METHODS = {
    "oracle": None,  # the posterior under the true parameters: the noise floor
    "scdecontx": {"background": False},
    "scdecontx+bg": {"background": True},
}
SHOWN = [
    ("mae_total", "MAE total"),
    ("worst_cluster_bias", "worst cluster bias"),
    ("mae_foreign", "MAE foreign"),
    ("counts_rel_error", "counts relative error"),
    ("marker_leak", "marker leak"),
    ("over_removal", "over-removal"),
]


def fit(sim, background, **kw):
    adata = ad.AnnData(sim.X)
    adata.obs_names = [f"c{i}" for i in range(adata.n_obs)]
    adata.var_names = [f"g{i}" for i in range(adata.n_vars)]
    adata.obs["cluster"] = pd.Categorical(sim.z.astype(str))
    bg = None
    if background:
        bg = ad.AnnData(sim.droplets)
        bg.obs_names = [f"d{i}" for i in range(bg.n_obs)]
        bg.var_names = adata.var_names
    start = time.perf_counter()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        dx.run(adata, "cluster", background=bg, **kw)
    seconds = time.perf_counter() - start
    fit_info = adata.uns["scdecontx"]["fit"]
    m = score(
        sim,
        adata.obs["scdecontx_contamination"].to_numpy(),
        adata.layers["scdecontx_counts"],
    )
    m.update(
        seconds=seconds,
        n_iter=int(fit_info["n_iter"][0]),
        converged=bool(fit_info["converged"][0]),
    )
    return m


def summary(df) -> str:
    """One table per contamination level: mean over seeds, methods as columns."""
    lines = [
        "# Soup scenarios",
        "",
        "Generated by `scripts/scenarios.py` from `tests/_soup.py`. Mean over "
        f"{df.seed.nunique()} seeds. *Total* is all soup counts; *foreign* is "
        "the soup counts from other clusters, the part the model can see. "
        "*Worst cluster bias* is the mean error of the cluster with the largest "
        "one. *Counts relative error* is ‖N̂ − N‖_F / ‖N‖_F against the true "
        "native counts N. *Marker leak* is the share of contaminating marker "
        "counts left in the corrected counts; *over-removal* the share of native "
        "counts removed.",
        "",
        "*oracle* is the posterior under the true parameters, the floor that "
        "sampling noise leaves to any method. Marker leak and over-removal count "
        "only one sign of the error, so even the oracle has nonzero values. Soup "
        "of the cell's own type lies on its native genes, so removing it raises "
        "over-removal: read over-removal against the oracle, not as lower is "
        "better. Counts relative error weighs both kinds of error.",
        "",
    ]
    for level in df.level.unique():
        for key, label in SHOWN:
            sel = df[df.level == level]
            tab = sel.pivot_table(
                index="scenario", columns="method", values=key, aggfunc="mean"
            )[list(METHODS)]
            lines += [f"## {level} contamination: {label}", ""]
            lines.append("| scenario | " + " | ".join(tab.columns) + " |")
            lines.append("|---" * (len(tab.columns) + 1) + "|")
            for name, row in tab.iterrows():
                vals = " | ".join(
                    f"{v:+.3f}" if "bias" in key else f"{v:.3f}" for v in row
                )
                lines.append(f"| {name} | {vals} |")
            lines.append("")
    not_conv = df[~df.converged]
    lines.append(f"Runs that did not converge: {len(not_conv)} of {len(df)}.")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true", help="one seed, 40% only")
    parser.add_argument(
        "--summary", action="store_true", help="rewrite the .md from the .csv"
    )
    args = parser.parse_args()
    if args.summary:
        df = pd.read_csv(RESULTS / "scenarios.csv")
        (RESULTS / "scenarios.md").write_text(summary(df))
        return
    seeds = SEEDS[:1] if args.quick else SEEDS
    levels = {"40%": LEVELS["40%"]} if args.quick else LEVELS

    rows = []
    for name, kw in SCENARIOS.items():
        for level, delta in levels.items():
            for seed in seeds:
                sim = simulate_soup(seed, delta=delta, **kw)
                for method, mkw in METHODS.items():
                    if mkw is None:
                        m = score(sim, *oracle(sim))
                        m.update(seconds=0.0, n_iter=0, converged=True)
                    else:
                        m = fit(sim, **mkw)
                    rows.append(
                        dict(scenario=name, level=level, seed=seed, method=method, **m)
                    )
                    print(
                        f"{name:13s} {level:3s} seed {seed} {method:12s} "
                        f"MAE total {m['mae_total']:.3f}  foreign {m['mae_foreign']:.3f}"
                        f"  {m['seconds']:.1f} s",
                        flush=True,
                    )
    df = pd.DataFrame(rows)
    suffix = "_quick" if args.quick else ""
    df.to_csv(RESULTS / f"scenarios{suffix}.csv", index=False, float_format="%.6g")
    (RESULTS / f"scenarios{suffix}.md").write_text(summary(df))


if __name__ == "__main__":
    main()
